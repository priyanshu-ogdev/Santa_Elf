# Optional Tight Bounded HiGHS MILP Polish
# ---------------------------------------------------------------------------

def _milp_polish(
    targets: list[int],
    seeds_set: set[int],
    cur_defs: dict[int, tuple[str, int, int]],
    candidate_recipes: dict[int, list[dict[int, tuple[str, int, int]]]],
) -> Optional[dict[int, tuple[str, int, int]]]:
    """
    Formulate a small MILP over the union of `cur_defs` and top compact
    target recipes (capped <= 700 candidate edges) via `scipy.optimize.milp` (HiGHS).
    Returns an improved acyclic `defs` dict, or None if unavailable / slower / larger.
    """
    try:
        import numpy as np
        import scipy.sparse as sp
        from scipy.optimize import milp, LinearConstraint, Bounds
    except ImportError:
        return None

    edge_set: set[tuple[str, int, int, int]] = set()
    for res, (op, a, b) in cur_defs.items():
        edge_set.add((op, a, b, res))

    for t in targets:
        recs = sorted(candidate_recipes.get(t, []), key=len)[:4]
        for rmap in recs:
            for res, (op, a, b) in rmap.items():
                edge_set.add((op, a, b, res))

    if len(edge_set) > 750 or len(edge_set) <= len(cur_defs):
        return None

    edges = sorted(edge_set)
    all_vals = set(targets)
    for _, a, b, res in edges:
        all_vals.add(a)
        all_vals.add(b)
        all_vals.add(res)
    non_seed = sorted(all_vals - seeds_set)
    val_to_idx = {v: i for i, v in enumerate(non_seed)}
    nv = len(non_seed)
    ne = len(edges)

    out_edges: dict[int, list[int]] = defaultdict(list)
    for ei, (_, _, _, res) in enumerate(edges):
        if res in val_to_idx:
            out_edges[val_to_idx[res]].append(ei)

    banned_cycles: list[list[int]] = []
    for _ in range(4):
        n_vars = nv + ne
        c = np.zeros(n_vars, dtype=float)
        c[:nv] = 1.0
        c[nv:] = 0.001

        lb_v = np.zeros(n_vars)
        ub_v = np.ones(n_vars)
        for t in targets:
            lb_v[val_to_idx[t]] = 1.0

        rows, cols, vals_sp = [], [], []
        b_l, b_u = [], []
        rc = 0

        for vi in range(nv):
            elist = out_edges.get(vi, [])
            if not elist:
                ub_v[vi] = 0.0
                continue
            rows.append(rc)
            cols.append(vi)
            vals_sp.append(1.0)
            for ei in elist:
                rows.append(rc)
                cols.append(nv + ei)
                vals_sp.append(-1.0)
            b_l.append(-np.inf)
            b_u.append(0.0)
            rc += 1

        for ei, (_, a, b, _) in enumerate(edges):
            if a in val_to_idx:
                rows.extend([rc, rc])
                cols.extend([nv + ei, val_to_idx[a]])
                vals_sp.extend([1.0, -1.0])
                b_l.append(-np.inf)
                b_u.append(0.0)
                rc += 1
            if b in val_to_idx and b != a:
                rows.extend([rc, rc])
                cols.extend([nv + ei, val_to_idx[b]])
                vals_sp.extend([1.0, -1.0])
                b_l.append(-np.inf)
                b_u.append(0.0)
                rc += 1

        for cyc in banned_cycles:
            for ei in cyc:
                rows.append(rc)
                cols.append(nv + ei)
                vals_sp.append(1.0)
            b_l.append(-np.inf)
            b_u.append(float(len(cyc) - 1))
            rc += 1

        A = sp.csc_matrix((vals_sp, (rows, cols)), shape=(rc, n_vars))
        res = milp(
            c=c,
            integrality=np.ones(n_vars),
            bounds=Bounds(lb_v, ub_v),
            constraints=LinearConstraint(A, b_l, b_u),
            options={"time_limit": 0.25, "mip_rel_gap": 0.01},
        )
        if res.x is None:
            return None

        sel_edges = [ei for ei in range(ne) if res.x[nv + ei] > 0.5]
        adj: dict[int, tuple[str, int, int]] = {}
        edge_by_res: dict[int, int] = {}
        for ei in sel_edges:
            op, a, b, rv = edges[ei]
            if rv not in adj and rv not in seeds_set:
                adj[rv] = (op, a, b)
                edge_by_res[rv] = ei

        # Check all targets reachable and cycle-free
        state: dict[int, int] = {}
        found_cyc: Optional[list[int]] = None
        path_vals: list[int] = []

        def dfs(u: int) -> bool:
            nonlocal found_cyc
            if u in seeds_set or state.get(u) == 1:
                return False
            if state.get(u) == 0:
                idx0 = path_vals.index(u)
                found_cyc = [edge_by_res[w] for w in path_vals[idx0:]]
                return True
            if u not in adj:
                return False
            state[u] = 0
            path_vals.append(u)
            _, pa, pb = adj[u]
            if dfs(pa) or dfs(pb):
                return True
            path_vals.pop()
            state[u] = 1
            return False

        for t in targets:
            if dfs(t):
                break

        if found_cyc is None:
            # Prune reachable subgraph
            keep: dict[int, tuple[str, int, int]] = {}
            stk = list(targets)
            vis = set(seeds_set)
            ok = True
            while stk:
                u = stk.pop()
                if u in vis:
                    continue
                if u not in adj:
                    ok = False
                    break
                vis.add(u)
                keep[u] = adj[u]
                _, pa, pb = adj[u]
                if pa not in vis:
                    stk.append(pa)
                if pb not in vis:
                    stk.append(pb)
            if ok and len(keep) < len(cur_defs):
                return keep
            return None
        banned_cycles.append(found_cyc)
    return None


