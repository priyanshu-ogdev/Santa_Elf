def dag_synthesizer_solve(puzzle: Puzzle, *, force_python: bool = False) -> list[Instruction]:
    """
    Solve `puzzle` using the 5-engine shared-DAG synthesizer, Rip-and-Reroute,
    optional bounded HiGHS MILP polish, Sethi-Ullman compiler, and dead-op cleanup.
    """
    if puzzle.value_limit < 40:
# [bundled]         from src.solvers import tiny_bfs
        return tiny_bfs.solve(puzzle)

# [bundled]     from src.verifier import verify_program
# [bundled]     from src.postpass import remove_dead_ops

    seeds_set = set(puzzle.seeds)
    targets = sorted(set(puzzle.targets) - seeds_set)
    if not targets:
        return []

    with DictEngine(puzzle, force_python=force_python) as de:
        smooth_map = _precompute_smooth_bpe(targets, de)
        latent_roots = _discover_latent_roots(targets, de.vl)

        orderings = [
            latent_roots + sorted(targets, key=lambda t: (t.bit_length(), t)),
            latent_roots + sorted(targets, key=lambda t: (0 if t in smooth_map else 1, t.bit_length(), t)),
        ]

        best_defs: Optional[dict[int, tuple[str, int, int]]] = None
        cand_recipes: dict[int, list[dict[int, tuple[str, int, int]]]] = defaultdict(list)

        for order in orderings:
            active_defs: dict[int, tuple[str, int, int]] = {}
            active_sorted = sorted(de.seeds)
            active_set = set(active_sorted)

            for item in order:
                col: list[dict[int, tuple[str, int, int]]] = [] if item in targets else None  # type: ignore[assignment]
                added = _synthesize_best_marginal(
                    item,
                    active_defs,
                    active_sorted,
                    de,
                    depth=2,
                    extra_cands=smooth_map.get(item),
                    recipe_collector=col,
                )
                if col:
                    cand_recipes[item].extend(col[:4])
                if added:
                    active_defs.update(added)
                    active_set.update(added.keys())
                    active_sorted = sorted(active_set)

            if all(t in active_defs or t in seeds_set for t in targets):
                if best_defs is None or len(active_defs) < len(best_defs):
                    best_defs = active_defs

        if best_defs is None:
# [bundled]             from src.solvers import binary_shared
            return binary_shared.solve(puzzle)

        def prune_dag(dmap: dict[int, tuple[str, int, int]]) -> dict[int, tuple[str, int, int]]:
            keep: dict[int, tuple[str, int, int]] = {}
            stk = list(targets)
            vis = set(seeds_set)
            while stk:
                u = stk.pop()
                if u in vis:
                    continue
                vis.add(u)
                op, a, b = dmap[u]
                keep[u] = (op, a, b)
                if a not in vis:
                    stk.append(a)
                if b not in vis:
                    stk.append(b)
            return keep

        cur_defs = prune_dag(best_defs)

        # Monotone Rip-and-Reroute sweeps
        for _ in range(2):
            improved = False
            for t in reversed(targets):
                keep_other: dict[int, tuple[str, int, int]] = {}
                stk = [x for x in targets if x != t]
                vis = set(seeds_set)
                while stk:
                    u = stk.pop()
                    if u in vis:
                        continue
                    vis.add(u)
                    op, a, b = cur_defs[u]
                    keep_other[u] = (op, a, b)
                    if a not in vis:
                        stk.append(a)
                    if b not in vis:
                        stk.append(b)

                if t in keep_other or t in seeds_set:
                    if len(keep_other) < len(cur_defs):
                        cur_defs = keep_other
                        improved = True
                    continue

                other_sorted = sorted(set(keep_other.keys()) | seeds_set)
                col_r: list[dict[int, tuple[str, int, int]]] = []
                new_add = _synthesize_best_marginal(
                    t,
                    keep_other,
                    other_sorted,
                    de,
                    depth=2,
                    extra_cands=smooth_map.get(t),
                    recipe_collector=col_r,
                )
                if col_r:
                    cand_recipes[t].extend(col_r[:3])
                if new_add is not None:
                    cand_defs = dict(keep_other)
                    cand_defs.update(new_add)
                    cand_defs = prune_dag(cand_defs)
                    if len(cand_defs) < len(cur_defs):
                        cur_defs = cand_defs
                        improved = True
            if not improved:
                break

        # Compile baseline winner
        best_prog = remove_dead_ops(puzzle, compile_dag(puzzle, cur_defs))

        # Optional bounded HiGHS MILP polish over union of top compact recipes
        milp_defs = _milp_polish(targets, seeds_set, cur_defs, cand_recipes)
        if milp_defs is not None:
            try:
                milp_prog = remove_dead_ops(puzzle, compile_dag(puzzle, milp_defs))
                if len(milp_prog) < len(best_prog) and verify_program(puzzle, milp_prog).valid:
                    best_prog = milp_prog
            except Exception:
                pass

        return best_prog

